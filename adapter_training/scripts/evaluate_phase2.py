"""
Phase 2 Evaluation Script — Evaluate Adapter Predictions

Designed to run locally (no GPU required).
Reads predictions.jsonl generated by predict_test_set.py and evaluates using:
  1. Schema Compliance (automatic)
  2. Preservation Rate (automatic)
  3. LLM-as-a-Judge (GPT-4o, reference-free, 3 sub-dimensions)

Usage:
    python evaluate_phase2.py
    python evaluate_phase2.py --predictions path/to/predictions.jsonl
    python evaluate_phase2.py --skip-judge   # Auto metrics only, no API cost
"""

